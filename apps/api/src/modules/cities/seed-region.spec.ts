describe('регион справочника городов (PN-1)', () => {
  it('все регионы набора — ровно названия Mapbox', () => {
    const regions = [...new Set(readCityRows().map((r) => r.region))].sort();
    expect(regions).toEqual([...MAPBOX_REGIONS].sort());
  });

  it('Ярославль — «Ярославская область», как у пункта из подсказки', () => {
    expect(readCityRows().find((r) => r.name === 'Ярославль')?.region).toBe('Ярославская область');
  });

  it('незнакомый вид региона — ошибка, а не тихий старый вид', () => {
    expect(() => mapboxRegion('Респ', 'Неизвестная')).toThrow(/Неизвестная/);
    expect(() => mapboxRegion('у', 'Тестовый')).toThrow(/Тестовый/);
  });
});
