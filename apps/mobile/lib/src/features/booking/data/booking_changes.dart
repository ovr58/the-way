import 'package:flutter/foundation.dart';

/// Брони пассажира изменились его действием во всплывающем окне — ответа водителя («Пришёл ответ»: оплата, отказ)
/// или отмены («Пришёл ответ», «Детали поездки - Лимит отмен», «Детали поездки - Отмена брони»). Окна открываются поверх оболочки (проверка событий) или поверх деталей, а
/// не из списка, поэтому «Мои заказы» и детали брони или заказа слушают это и перечитываются сразу.
final bookingChanges = ValueNotifier<int>(0);

/// Сообщить слушателям: брони на сервере изменились.
void notifyBookingsChanged() => bookingChanges.value++;
